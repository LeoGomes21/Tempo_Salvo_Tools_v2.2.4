    def _locale_candidates(self):
        """
        Retorna possíveis nomes de idioma para procurar arquivos .qm.

        Exemplo:
        - en_US -> en_US, en
        - es_ES -> es_ES, es
        - pt_BR -> pt_BR, pt
        """
        locale = QSettings().value("locale/userLocale", "", type=str)

        if not locale:
            locale = QSettings().value("locale/globalLocale", "", type=str)

        locale = str(locale or "").replace("-", "_").strip()

        candidates = []

        if locale:
            candidates.append(locale)

            lang = locale.split("_")[0]
            if lang and lang not in candidates:
                candidates.append(lang)

        return candidates

    def _install_translator(self):
        """
        Carrega o arquivo .qm conforme o idioma do QGIS.

        Procura nesta ordem:
        - i18n/TempoSalvoTools_en_US.qm
        - i18n/TempoSalvoTools_en.qm
        """
        for loc in self._locale_candidates():
            locale_path = os.path.join(
                self.plugin_dir,
                "i18n",
                f"TempoSalvoTools_{loc}.qm")

            if not os.path.exists(locale_path):
                continue

            translator = QTranslator()

            if translator.load(locale_path):
                QCoreApplication.installTranslator(translator)
                self.translator = translator
                break

